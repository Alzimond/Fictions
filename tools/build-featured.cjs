/* EDITORIAL BUILD — run from any directory:
     node path/to/signal-press/tools/build-featured.cjs
   EDIT featured/manifest.json, the named article .txt files and banner .art.txt files.
   ADD another manifest object to add a card. ORDER the objects to reorder cards.
   examples.js is generated: do not paste long seeds into it by hand.
   This script only writes local files. It never uploads or publishes anything. */
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict'),zlib=require('node:zlib');
const root=path.resolve(__dirname,'..'),Codec=require(path.join(root,'codec.js'));
function source(name){if(typeof name!=='string')throw Error('Source filename required');const target=path.resolve(root,'featured',name);if(!target.startsWith(path.join(root,'featured')+path.sep))throw Error('Source must stay in featured/');return fs.readFileSync(target,'utf8')}
(async()=>{
  const manifest=JSON.parse(fs.readFileSync(path.join(root,'featured/manifest.json'),'utf8'));assert(manifest.length>0,'At least one featured article is needed');
  const examples=[],metrics=[];
  for(const entry of manifest){
    // Easiest way to PIN an editor-made post: save its seed in featured/ and
    // add {"label":"Card title","seedFile":"my-post.seed.txt"} to the manifest.
    const doc=entry.seedFile
      ? await Codec.decode(source(entry.seedFile).trim())
      : {v:2,title:entry.title,author:entry.author,deck:entry.deck||'',body:source(entry.body).replaceAll('\r\n','\n').trim(),image:source(entry.image).replace(/[\r\n]/g,'')};
    const seed=await Codec.encode(doc);assert.deepEqual(await Codec.decode(seed),doc);
    const words=doc.body.trim().split(/\s+/u).filter(Boolean).length;
    examples.push({label:entry.label||doc.title,title:doc.title,words,seed});
    const old='IFB2.'+zlib.gzipSync(JSON.stringify(Codec.validate(doc))).toString('base64url');
    metrics.push({title:doc.title,words,bodyCharacters:Array.from(doc.body).length,bannerCells:doc.image.length,bannerTones:new Set(doc.image).size,oldSeedCharacters:old.length,seedCharacters:seed.length,savedCharacters:old.length-seed.length,format:seed.slice(0,4)});
  }
  fs.writeFileSync(path.join(root,'examples.js'),'// GENERATED by tools/build-featured.cjs. Edit featured/manifest.json and its source files.\nconst EXAMPLES = '+JSON.stringify(examples,null,2)+';\n');
  fs.writeFileSync(path.join(root,'example-seeds.txt'),examples.map((e,i)=>`EXAMPLE ${i+1}: ${e.title}\n${e.words} words | ${e.seed.length} seed characters\nCopy the entire following line into OPEN SEED:\n${e.seed}\n`).join('\n'));
  fs.writeFileSync(path.join(root,'featured/size-report.json'),JSON.stringify(metrics,null,2)+'\n');console.table(metrics);
})().catch(error=>{console.error(error);process.exitCode=1});
